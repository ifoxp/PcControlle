_README = """Промпти сортувальника фото/відео PC Control.

photo.txt — інструкція моделі для фото, video.txt — для відео.
Редагуй у Блокноті й збережи — діє з наступного файлу, перезапуск не потрібен.
Скинути до стандартних: Налаштування → Сортувальник → «Скинути промпти».

Підстановки (програма замінює їх перед відправкою моделі):
  {filename}   — ім'я файлу (фото і відео)
  {num_frames} — скільки кадрів з відео прикріплено (відео)
  {duration}   — тривалість відео (відео)
  {timeline}   — час кожного кадру: "#1 — 0:01, #2 — 0:04, ..." (відео)

Модель має повернути JSON з полями "reason" і "is_trash" — цю схему програма
задає сама, тож у тексті достатньо пояснити, що вважати сміттям.
"""

_FILES = {
    "image": (paths.PROMPT_IMAGE_FILE, PROMPT_IMAGE),
    "video": (paths.PROMPT_VIDEO_FILE, PROMPT_VIDEO),
}


def ensure_files() -> None:
    """Створює файли промптів зі стандартним текстом, якщо їх ще немає."""
    paths.PROMPTS_DIR.mkdir(parents=True, exist_ok=True)
    for path, default in _FILES.values():
        if not path.exists():
            paths.atomic_write_text(path, default)
    readme = paths.PROMPTS_DIR / "README.txt"
    if not readme.exists():
        paths.atomic_write_text(readme, _README)


def load(kind: str) -> str:
    """Актуальний промпт ("image" | "video"). Порожній/битий файл — стандартний."""
    path, default = _FILES[kind]
    try:
        ensure_files()
        raw = path.read_bytes()
        try:
            text = raw.decode("utf-8-sig")
        except UnicodeDecodeError:
            text = raw.decode("cp1251")  # збережено з Блокнота в ANSI
        return text.strip() or default
    except Exception:
        return default


def reset() -> None:
    """Перезаписує обидва файли стандартними текстами."""
    paths.PROMPTS_DIR.mkdir(parents=True, exist_ok=True)
    for path, default in _FILES.values():
        paths.atomic_write_text(path, default)
